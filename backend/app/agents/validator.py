from dotenv import load_dotenv
from langchain_openai import ChatOpenAI

from app.models.project import (
    ProjectPlan,
    ArchitecturePlan,
    GeneratedProject,
    ValidationResult,
)

load_dotenv()


llm = ChatOpenAI(
    model="gpt-6-luna"
)

validator_llm = llm.with_structured_output(
    ValidationResult
)


def validate_project(
    project_plan: ProjectPlan,
    architecture: ArchitecturePlan,
    generated_project: GeneratedProject,
) -> ValidationResult:

    files_context = []

    for file in generated_project.files:

        files_context.append(
            f"""
============================================================
FILE: {file.path}
============================================================

PURPOSE:
{file.purpose}

CONTENT:
{file.content}
"""
        )

    project_files = "\n".join(
        files_context
    )

    prompt = f"""
You are the Validator Agent inside an autonomous
software engineering platform.

Your responsibility is to perform a deep quality,
correctness, security, and architecture validation
of a software project generated by another AI agent.

Do NOT assume the generated project is correct.

You must inspect the ACTUAL FILE CONTENT provided below.

============================================================
PROJECT REQUIREMENT
============================================================

{project_plan.model_dump_json(indent=2)}

============================================================
ARCHITECTURE
============================================================

{architecture.model_dump_json(indent=2)}

============================================================
GENERATED PROJECT FILES
============================================================

{project_files}

============================================================
VALIDATION FRAMEWORK
============================================================

Perform ALL of the following checks.

------------------------------------------------------------
1. PROJECT COMPLETENESS
------------------------------------------------------------

Check whether the generated project contains the files
and components reasonably required by the architecture.

Look for:

- Missing source files
- Missing configuration files
- Missing tests
- Missing environment configuration
- Missing deployment configuration
- Missing database configuration
- Missing documentation when required

Do not demand files that are clearly unnecessary
for the selected technology.

------------------------------------------------------------
2. ARCHITECTURE COMPLIANCE
------------------------------------------------------------

Compare the implementation against the architecture.

Check:

- Backend technology
- Frontend technology
- Database
- Authentication
- Infrastructure
- Directory organization
- Separation of responsibilities
- API structure
- Data-access architecture

Report architectural deviations.

------------------------------------------------------------
3. CODE CORRECTNESS
------------------------------------------------------------

Inspect the actual source code.

Look for:

- Syntax problems
- Obvious runtime errors
- Undefined variables
- Incorrect imports
- Missing functions
- Incorrect function calls
- Broken references
- Invalid configuration
- Incorrect paths
- Inconsistent naming
- Obvious logic errors

Do not report theoretical problems without evidence
in the supplied source.

------------------------------------------------------------
4. DEPENDENCY CONSISTENCY
------------------------------------------------------------

Inspect dependency files such as:

- package.json
- requirements.txt
- pyproject.toml
- pom.xml
- build.gradle
- Dockerfile
- docker-compose.yml

Check whether:

- Imported libraries are declared
- Declared dependencies appear reasonable
- Commands reference installed tools
- Versions are internally consistent
- Build commands match the project structure

------------------------------------------------------------
5. CONFIGURATION VALIDATION
------------------------------------------------------------

Inspect:

- Environment variables
- Database URLs
- API configuration
- Ports
- Docker configuration
- Application startup configuration

Identify:

- Hardcoded secrets
- Invalid configuration
- Localhost assumptions where inappropriate
- Missing environment variables
- Broken service names
- Configuration mismatches

------------------------------------------------------------
6. SECURITY VALIDATION
------------------------------------------------------------

Look for obvious security problems including:

- Hardcoded API keys
- Passwords
- Access tokens
- Private keys
- Insecure authentication
- Missing authorization checks
- SQL injection risks
- Unsafe command execution
- Unsafe file handling
- Debug credentials
- Sensitive information committed to source

Never expose a secret value in the validation response.

If a secret is found, describe it generically.

------------------------------------------------------------
7. TESTING VALIDATION
------------------------------------------------------------

Inspect the actual test files.

Check whether tests exist when required.

Look for:

- Missing tests
- Broken imports
- Tests that cannot execute
- Tests unrelated to the implementation
- Missing important scenarios
- Authentication tests
- Error handling tests
- Edge cases
- Integration tests when required

Do not require integration tests for a project
where they are clearly unnecessary.

------------------------------------------------------------
8. DEPLOYMENT VALIDATION
------------------------------------------------------------

If deployment configuration exists, inspect it.

Check:

- Dockerfile
- Docker Compose
- startup commands
- exposed ports
- environment variables
- health checks
- production configuration

Look for inconsistencies between the application
and deployment configuration.

------------------------------------------------------------
9. CODE QUALITY
------------------------------------------------------------

Evaluate:

- Modularity
- Separation of concerns
- Maintainability
- Naming
- Duplication
- Error handling
- Logging
- Configuration management
- Production readiness

Do not reject a project simply because it could be
written differently.

Only report meaningful quality issues.

------------------------------------------------------------
10. REQUIREMENT COVERAGE
------------------------------------------------------------

Compare the implementation against the original
project requirements.

Determine whether the requested functionality
is actually represented in the generated files.

Identify missing major requirements.

============================================================
SCORING
============================================================

Calculate an overall score from 0 to 100.

Use this approximate weighting:

Correctness:
30 points

Architecture:
15 points

Requirement coverage:
15 points

Security:
15 points

Testing:
10 points

Configuration/dependencies:
5 points

Deployment:
5 points

Code quality:
5 points

A project with a serious blocking runtime,
security, or architectural problem should not receive
a high score.

============================================================
PASS / FAIL RULE
============================================================

Set passed = true only when:

- There are no critical correctness problems
- There are no critical security problems
- Major requirements are implemented
- Architecture is substantially respected
- Required configuration is coherent
- The project is reasonably executable
- No major blocking issue remains

Warnings alone should not cause failure.

============================================================
IMPORTANT RULES
============================================================

1. Inspect the actual file contents.
2. Do not invent files.
3. Do not invent errors.
4. Every issue must be supported by evidence.
5. Distinguish critical issues from warnings.
6. Prioritize issues that can actually prevent execution.
7. Prioritize security issues.
8. Prefer concrete explanations.
9. Provide actionable recommendations.
10. Keep recommendations aligned with the existing architecture.
11. Do not introduce unnecessary technologies.
12. Do not expose secrets.
13. Do not merely summarize the project.
14. Return a structured ValidationResult.
15. Score the project honestly.

Your output must contain:

- passed
- score
- issues
- warnings
- recommendations
"""

    result = validator_llm.invoke(
        prompt
    )

    return result